package com.agnosticrouter.decision.infrastructure.persistence;

import com.agnosticrouter.decision.domain.model.AiProvider;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.jdbc.JdbcTest;
import org.springframework.context.annotation.Import;
import org.springframework.jdbc.core.JdbcTemplate;
import static org.junit.jupiter.api.Assertions.*;

@JdbcTest(properties = "spring.sql.init.mode=never")
@Import(JdbcAiProviderStore.class)
class JdbcAiProviderStoreTest {
    @Autowired JdbcTemplate jdbc;
    @Autowired JdbcAiProviderStore store;
    @BeforeEach void schema() {
        jdbc.execute("CREATE SCHEMA IF NOT EXISTS decision_engine");
        jdbc.execute("CREATE TABLE IF NOT EXISTS decision_engine.ai_provider(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name VARCHAR(160),base_url VARCHAR(1000),endpoint_path VARCHAR(200),model VARCHAR(160),language VARCHAR(30),auth_type VARCHAR(30),api_key_header VARCHAR(80),encrypted_api_key VARCHAR(4000),enabled BOOLEAN,default_slot INTEGER UNIQUE,CHECK(default_slot IS NULL OR (default_slot=1 AND enabled=TRUE)))");
    }
    private AiProvider save(String name) { return store.save(new AiProvider(null, name, "https://test.invalid", "/v1/systemone", "m", "es", "BEARER", "X-Api-Key", "ciphertext", true, false)); }
    @Test void storesCredentialsOnlyAsCiphertextAndKeepsOneSelectedProvider() {
        var first = save("First"); var second = save("Second");
        store.selectDefault(first.id()); assertEquals(first.id(), store.findDefault().orElseThrow().id());
        store.selectDefault(second.id()); assertEquals(second.id(), store.findDefault().orElseThrow().id());
        assertEquals(1, store.findAll().stream().filter(AiProvider::defaultProvider).count());
        assertEquals("ciphertext", jdbc.queryForObject("SELECT encrypted_api_key FROM decision_engine.ai_provider WHERE id=?", String.class, second.id()));
        store.clearDefault(); assertTrue(store.findDefault().isEmpty());
    }
}
